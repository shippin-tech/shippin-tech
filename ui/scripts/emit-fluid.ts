import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { calculateClamp, calculateSpaceScale, calculateTypeScale } from 'utopia-core';
import { viewport } from '../src/lib/token/viewport.ts';

const root = dirname(fileURLToPath(import.meta.url));
const out = resolve(root, '../src/lib/token/fluid.css');

const type = calculateTypeScale({
	minWidth: viewport.minWidth,
	maxWidth: viewport.maxWidth,
	minFontSize: viewport.type.minFontSize,
	maxFontSize: viewport.type.maxFontSize,
	minTypeScale: viewport.type.minTypeScale,
	maxTypeScale: viewport.type.maxTypeScale,
	negativeSteps: viewport.type.negativeSteps,
	positiveSteps: viewport.type.positiveSteps,
	relativeTo: 'viewport',
	labelStyle: 'tshirt'
});

const space = calculateSpaceScale({
	minWidth: viewport.minWidth,
	maxWidth: viewport.maxWidth,
	minSize: viewport.space.minSize,
	maxSize: viewport.space.maxSize,
	negativeSteps: [...viewport.space.negativeSteps],
	positiveSteps: [...viewport.space.positiveSteps],
	relativeTo: 'viewport'
});

const lines = [
	'/* Generated by ui/scripts/emit-fluid.ts from viewport.ts. Do not edit. */',
	':root {'
];

for (const step of type) {
	if (step.wcagViolation) {
		throw new Error(`Type step ${step.label} fails WCAG 1.4.4 between ${step.wcagViolation.from} and ${step.wcagViolation.to}`);
	}
	lines.push(`\t--step-${step.label}: ${step.clamp};`);
}

for (const size of [...space.sizes, ...space.oneUpPairs]) {
	lines.push(`\t--x-${size.label}: ${size.clamp};`);
	lines.push(`\t--y-${size.label}: ${size.clamp.replaceAll('vi', 'vb')};`);
}

for (const [name, pair] of Object.entries(viewport.images)) {
	const clamp = calculateClamp({
		minWidth: viewport.minWidth,
		maxWidth: viewport.maxWidth,
		minSize: pair[0],
		maxSize: pair[1],
		relativeTo: 'viewport'
	});
	lines.push(`\t--img-${name}: ${clamp};`);
}

lines.push(
	`\t--measure: ${calculateClamp({
		minWidth: viewport.minWidth,
		maxWidth: viewport.maxWidth,
		minSize: viewport.measure[0],
		maxSize: viewport.measure[1],
		relativeTo: 'viewport'
	})};`
);
lines.push(
	`\t--aside: ${calculateClamp({
		minWidth: viewport.minWidth,
		maxWidth: viewport.maxWidth,
		minSize: viewport.aside[0],
		maxSize: viewport.aside[1],
		relativeTo: 'viewport'
	})};`
);

lines.push('\t--space-1: var(--x-3xs);');
lines.push('\t--space-2: var(--x-2xs);');
lines.push('\t--space-3: var(--x-s);');
lines.push('\t--space-4: var(--x-m);');
lines.push('}');
lines.push('');

writeFileSync(out, lines.join('\n'));
console.log(out);
